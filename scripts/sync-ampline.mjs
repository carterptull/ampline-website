// Copies ampline-claude's renderer source byte-for-byte into one ES module.
// Each CommonJS file is pre-wrapped in a factory function HERE, at sync time,
// because the site's CSP (script-src 'self', no 'unsafe-eval') forbids eval/new Function.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKG = join(ROOT, 'node_modules', 'ampline-claude');
const OUT = join(ROOT, 'site', 'js', 'runtime', 'factories.generated.js');

// git.js / task.js / cache.js / claudeDir.js / install.js are deliberately NOT vendored:
// they need fs/child_process. The browser gets fakes (runtime/fakes.js) or stubs instead.
export const VENDORED = [
  'lib/colors.js',
  'lib/bar.js',
  'lib/layout.js',
  'lib/usage.js',
  'lib/config.js',
  'lib/render.js',
  'lib/segments/model.js',
  'lib/segments/context.js',
  'lib/segments/rateLimits.js',
  'lib/segments/cost.js',
  'lib/segments/pr.js',
  'lib/segments/subagents.js',
];

export function generate() {
  const version = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8')).version;
  const parts = [
    '// GENERATED by scripts/sync-ampline.mjs. Do not edit by hand.',
    `// Source: ampline-claude@${version} (node_modules/ampline-claude/lib), embedded verbatim.`,
    `export const VERSION = ${JSON.stringify(version)};`,
    'export const FACTORIES = {',
  ];
  for (const rel of VENDORED) {
    const id = rel.replace(/^lib\//, '').replace(/\.js$/, '');
    const src = readFileSync(join(PKG, rel), 'utf8');
    parts.push(`${JSON.stringify(id)}: function (module, exports, require, process) {\n${src}\n},`);
  }
  parts.push('};', '');
  return parts.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const next = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch {}
    if (current !== next) {
      console.error('factories.generated.js is stale: run `npm run sync` and commit the result.');
      process.exit(1);
    }
    console.log('factories.generated.js is in sync.');
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, next);
    console.log(`Wrote ${OUT}`);
  }
}
